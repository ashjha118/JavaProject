package WeekFirst;

public class profit {

	public static void main(String[] args) {
		
		double cost_price=141;
		double sell_price=191;
		double profit=sell_price-cost_price;
		double profit_percentage=profit/cost_price*100;
		System.out.print("The Cost Price is INR 141 and Selling Price is INR 191");
		System.out.println();
		System.out.print("The Profit is INR "+ profit+"and the Profit Percentage is "+profit_percentage );
		
	}

}

